/** Building blocks of the chart reports (Destiny Matrix, Pythagoras Square): rendered on screen and in the printable PDF. */
export type Lang = 'en' | 'hi';
export type Blk =
  | { k: 'p'; t: string }
  | { k: 'h'; t: string }
  | { k: 'tip'; t: string }
  | { k: 'list'; items: string[] }
  | { k: 'tiles'; items: { label: string; value: string }[] }
  | { k: 'table'; head: string[]; rows: string[][]; hl?: number[] }
  | { k: 'svg'; svg: string; caption?: string };
export interface ReportSection { id: string; title: string; blocks: Blk[] }
export interface WrittenReport { title: string; subtitle: string; summary: string; sections: ReportSection[] }

const MONTHS = {
  en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
  hi: ['जनवरी', 'फ़रवरी', 'मार्च', 'अप्रैल', 'मई', 'जून', 'जुलाई', 'अगस्त', 'सितंबर', 'अक्टूबर', 'नवंबर', 'दिसंबर'],
};
export const fmtDob = (iso: string, lang: Lang) => { const [y, m, d] = iso.split('-').map(Number); return `${d} ${MONTHS[lang][m - 1]} ${y}`; };

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]!));
/** Print HTML for one block (the SVG is generated by our own code from numbers, so it is inserted as is). */
export function blockHtml(b: Blk): string {
  switch (b.k) {
    case 'p': return `<p>${esc(b.t)}</p>`;
    case 'h': return `<h3>${esc(b.t)}</h3>`;
    case 'tip': return `<p class="tip">${esc(b.t)}</p>`;
    case 'list': return `<ul>${b.items.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>`;
    case 'tiles': return `<div class="k">${b.items.map((x) => `<div>${esc(x.label)}<b>${esc(x.value)}</b></div>`).join('')}</div>`;
    case 'table': return `<table><thead><tr>${b.head.map((h) => `<th>${esc(h)}</th>`).join('')}</tr></thead><tbody>${b.rows.map((r, i) => `<tr${b.hl?.includes(i) ? ' class="hl"' : ''}>${r.map((c) => `<td>${esc(c)}</td>`).join('')}</tr>`).join('')}</tbody></table>`;
    case 'svg': return `<figure class="chart">${b.svg}${b.caption ? `<figcaption>${esc(b.caption)}</figcaption>` : ''}</figure>`;
  }
}
export { esc as escHtml };
