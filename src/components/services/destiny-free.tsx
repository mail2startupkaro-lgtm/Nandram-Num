'use client';
/** Free instant Destiny Matrix chart for the service page (lead magnet) – same engine as the admin report. */
import * as React from 'react';
import { useApp } from '@/components/layout/providers';
import { trackEvent, trackCalculatorUse } from '@/lib/client/analytics';
import { arcana } from '@/lib/destiny/arcana';
import { ageEnergy, ageRange, destinyMatrix, exactAge, type DestinyMatrix } from '@/lib/destiny/matrix';
import { destinySvg } from '@/lib/destiny/svg';
import { DobForm, Upsell, useDob } from './chart-tool-parts';

export function DestinyMatrixFree({ whatsapp }: { whatsapp: string }) {
  const { lang } = useApp();
  const hi = lang === 'hi';
  const { dob, setDob, valid } = useDob();
  const [m, setM] = React.useState<DestinyMatrix | null>(null);
  const run = () => { if (!valid) return; setM(destinyMatrix(dob)); trackEvent('chart_tool_run', { tool: 'destiny' }); trackCalculatorUse('destiny-matrix'); };
  const nm = (n: number) => `${n} · ${arcana(n).name[lang]}`;
  const age = m ? exactAge(m.dob, new Date().toISOString().slice(0, 10)) : 0;
  const now = m ? ageEnergy(m, age) : null;
  const keys: [string, number, string][] = m ? [
    [hi ? 'व्यक्तित्व (A)' : 'Personality (A)', m.A, arcana(m.A).plus[lang]],
    [hi ? 'सहज क्षेत्र – केंद्र (E)' : 'Comfort zone – centre (E)', m.E, arcana(m.E).plus[lang]],
    [hi ? 'प्रतिभा (B)' : 'Talents (B)', m.B, arcana(m.B).talent[lang]],
  ] : [];
  return (
    <div className="glass space-y-6 rounded-2xl border border-gold/30 p-5 sm:p-6">
      <DobForm id="dm-free-dob" dob={dob} setDob={setDob} onSubmit={run} label={hi ? 'मेरी मैट्रिक्स दिखाएँ' : 'Show my matrix'} hi={hi} />
      {m && (
        <div className="grid gap-6 lg:grid-cols-[minmax(0,1fr)_minmax(0,1fr)] lg:items-start">
          {/* The SVG is generated by our own engine from the date only. */}
          <div className="mx-auto w-full max-w-md overflow-hidden rounded-xl" dangerouslySetInnerHTML={{ __html: destinySvg(m) }} />
          <div className="space-y-4">
            <div className="grid grid-cols-3 gap-2 text-center">
              {[[hi ? 'केंद्र' : 'Centre', m.E], [hi ? 'धन-बिंदु' : 'Money point', m.money], [hi ? 'कर्म-पूँछ' : 'Karmic tail', m.karmicTail.join('-')]].map(([k, v]) => (
                <div key={String(k)} className="rounded-lg border border-gold/30 bg-background/40 p-2"><p className="text-[11px] text-muted-foreground">{k}</p><p className="font-serif text-xl font-bold text-gold">{v}</p></div>
              ))}
            </div>
            {keys.map(([k, n, t]) => (
              <div key={k} className="rounded-lg border border-gold/20 bg-background/30 p-3">
                <p className="text-xs font-semibold uppercase tracking-wider text-gold">{k}</p>
                <p className="font-semibold">{nm(n)}</p>
                <p className="text-sm text-muted-foreground">{t}</p>
              </div>
            ))}
            {now && <p className="rounded-lg bg-gold/10 p-3 text-sm"><b>{hi ? 'अभी आपकी अवधि' : 'Your current period'} ({ageRange(now.age)}):</b> {nm(now.value)} – {arcana(now.value).keys[lang]}</p>}
          </div>
          <div className="lg:col-span-2">
            <Upsell hi={hi} whatsapp={whatsapp} service="Destiny Matrix" blur={hi ? 'धन चैनल, प्रेम चैनल, कर्म-पूँछ, पारिवारिक रेखाएँ, चार जीवन उद्देश्य, चक्र स्वास्थ्य मानचित्र और 0–80 वर्ष की पूरी समयरेखा। आपकी हर ऊर्जा का प्लस और माइनस, और प्लस में रहने के सरल उपाय।' : 'Money channel, love channel, karmic tail, family lines, four life purposes, chakra health map and the full 0–80 timeline. Every energy in its plus and minus, with simple ways to stay in the plus.'} text={hi ? 'पूरे विश्लेषण में आपकी मैट्रिक्स के सभी बिंदु सरल भाषा में – धन, प्रेम, कर्म-पूँछ, उद्देश्य, स्वास्थ्य और वर्ष-दर-वर्ष समयरेखा।' : 'The full analysis reads every point of your matrix in plain language – money, love, karmic tail, purposes, health and your year-by-year timeline.'} />
          </div>
        </div>
      )}
    </div>
  );
}

