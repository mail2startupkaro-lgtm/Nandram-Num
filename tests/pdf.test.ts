import { afterAll, describe, expect, it } from 'vitest';
import { PDFDocument } from 'pdf-lib';
import { generateNumerology, verhoeffCheckDigit } from '@/lib/numerology';
import { BANNED_TERMS } from '@/lib/narrative/filter';
import { closeBrowser, renderReportPdf } from '@/lib/pdf/render';
import { buildBodyHtml, buildCoverHtml } from '@/lib/pdf/template';
import { generateNarrative } from '@/lib/narrative/service';
import { DEFAULT_BRANDING, resolveTheme, THEMES, type ThemeId } from '@/lib/pdf/themes';

const aadhaar = '23456789012' + verhoeffCheckDigit('23456789012');
const result = generateNumerology({
  fullName: 'Rahul Kumar Sharma', commonName: 'Rahul Sharma', hindiName: 'राहुल शर्मा', gender: 'male', dob: '28-08-1990', profession: 'Software engineer',
  maritalStatus: 'engaged', concerns: ['career', 'marriage'], mobile: '9876543210', aadhaar, aadhaarConsent: true,
  partner: { name: 'Priya Verma', gender: 'female', dob: '15-05-1992' },
}, { asOf: { day: 3, month: 11, year: 2026 } });

async function pageTexts(pdf: Uint8Array): Promise<string[]> {
  const pdfjs = await import('pdfjs-dist/legacy/build/pdf.mjs');
  const doc = await pdfjs.getDocument({ data: pdf.slice(), isEvalSupported: false, disableFontFace: true, verbosity: 0 }).promise;
  const out: string[] = [];
  for (let i = 1; i <= doc.numPages; i++) out.push((await (await doc.getPage(i)).getTextContent()).items.map((x) => ('str' in x ? x.str : '')).join(' '));
  await doc.destroy();
  return out;
}

afterAll(async () => { await closeBrowser(); });

describe('PDF report', () => {
  let pdf: Uint8Array; let texts: string[]; let toc: Record<string, number>; let ms = 0;

  it('renders the complete report in under 20 seconds with 15–40 pages', async () => {
    const out = await renderReportPdf({ result, theme: 'royal-gold-maroon' });
    pdf = out.pdf; toc = out.tocPages; ms = out.ms;
    texts = await pageTexts(pdf);
    expect(ms).toBeLessThan(20_000);
    expect(out.pageCount).toBeGreaterThanOrEqual(15);
    expect(out.pageCount).toBeLessThanOrEqual(40);
  }, 60_000);

  it('has brand-only metadata and no generator traces', async () => {
    const doc = await PDFDocument.load(pdf, { updateMetadata: false });
    expect(doc.getProducer()).toBe(DEFAULT_BRANDING.brandName);
    expect(doc.getCreator()).toBe(DEFAULT_BRANDING.brandName);
    expect(doc.getAuthor()).toBe(DEFAULT_BRANDING.brandName);
    const raw = Buffer.from(pdf).toString('latin1');
    for (const s of ['Skia', 'Chromium', 'HeadlessChrome', 'pdf-lib', 'Playwright']) expect(raw).not.toContain(s);
  });

  it('contains no AI words, banned phrases, full Aadhaar or full mobile number', () => {
    const all = texts.join('\n');
    expect(all).not.toMatch(/\b(AI|artificial intelligence|language model|generated by|algorithm)\b/i);
    for (const b of BANNED_TERMS) expect(all.toLowerCase()).not.toContain(b);
    expect(all.replace(/\s/g, '')).not.toContain(aadhaar);
    expect(all.replace(/\s/g, '')).not.toContain('9876543210');
    expect(all).toContain('XXXX-XXXX-');
  });

  it('table of contents page numbers point at the right pages', () => {
    // body page n = PDF page n + 1 (the cover is unnumbered)
    expect(Object.keys(toc)).toEqual(expect.arrayContaining(['glance', 'core', 'grid', 'kua', 'timing', 'life', 'name', 'numbers', 'couple', 'remedies', 'closing']));
    expect(texts[toc.grid]).toContain('Lo Shu Grid Analysis');
    expect(texts[toc.remedies]).toContain('Remedies & Solutions');
    expect(texts[1]).toMatch(new RegExp(`Lo Shu Grid Analysis.*${toc.grid}`));
  });

  it('prints the disclaimer on every body page', () => {
    for (const t of texts.slice(1)) expect(t).toContain('Numerology is traditional guidance');
  });

  it('renders every theme', async () => {
    for (const id of Object.keys(THEMES) as ThemeId[]) {
      const out = await renderReportPdf({ result, theme: id, narrative: await generateNarrative(result) });
      expect(out.pageCount, id).toBeGreaterThanOrEqual(15);
      expect(out.ms, id).toBeLessThan(20_000);
    }
  }, 120_000);

  it('white-label branding and colours are applied', async () => {
    const narrative = await generateNarrative(result);
    const branding = { ...DEFAULT_BRANDING, brandName: 'Shubh Ank Studio', expertName: 'Acharya Meera', colours: { primary: '#123456' } };
    const theme = resolveTheme('cosmic-blue', branding);
    const inp = { result, narrative, theme, branding, reportDate: '2026-11-03' };
    expect(theme.primary).toBe('#123456');
    expect(buildCoverHtml(inp)).toContain('Acharya Meera');
    expect(buildBodyHtml(inp, null, '<svg></svg>').html).toContain('#123456');
  });
});
