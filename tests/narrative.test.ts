import { describe, expect, it, vi } from 'vitest';
import { generateNumerology, verhoeffCheckDigit } from '@/lib/numerology';
import {
  AnthropicProvider, BANNED_TERMS, buildPlan, checkNumbers, clientContext, collectNumbers, configFromEnv, forbiddenHits,
  generateNarrative, MemoryCache, numbersInText, postProcess, systemPrompt, type LlmProvider,
} from '@/lib/narrative';
import { KNOWLEDGE_SEED } from '@/lib/narrative/knowledge/seed';

const asOf = { day: 3, month: 11, year: 2026 };
const aadhaar = '23456789012' + verhoeffCheckDigit('23456789012');
const result = generateNumerology({
  fullName: 'Rahul Kumar Sharma', commonName: 'Rahul Sharma', gender: 'male', dob: '28-08-1990', profession: 'Software engineer',
  maritalStatus: 'engaged', concerns: ['career', 'marriage'], mobile: '9876543210', aadhaar, aadhaarConsent: true,
  partner: { name: 'Priya Verma', gender: 'female', dob: '15-05-1992' },
}, { asOf });

describe('post-processing filter', () => {
  it('removes machine-sounding phrases, emojis and extra em dashes', () => {
    const out = postProcess("It's important to note that your path is bright ✨. Furthermore, let us delve into the tapestry of your numbers — your Moolank — and unlock your potential — truly. In conclusion, embark on this journey.");
    for (const t of ['important to note', 'Furthermore', 'delve', 'tapestry', 'unlock', 'In conclusion', 'embark', 'journey', '✨']) expect(out).not.toContain(t);
    expect((out.match(/—/g) ?? []).length).toBeLessThanOrEqual(1);
    expect(out).toMatch(/^Your path is bright/);
  });
  it('removes self-references to AI', () => {
    const out = postProcess('As an AI language model, I can say your Moolank is 1. This was generated by AI.');
    expect(out.toLowerCase()).not.toMatch(/\bai\b|language model|generated/);
  });
  it('drops sentences repeated in earlier sections', () => {
    const seen = new Set<string>();
    postProcess('Your Moolank brings strong leadership to everything you do.', { seenSentences: seen });
    const second = postProcess('Your Moolank brings strong leadership to everything you do. A new idea appears here instead.', { seenSentences: seen });
    expect(second).toBe('A new idea appears here instead.');
  });
  it('flags fear-inducing or self-referential words', () => {
    expect(forbiddenHits('There may be an accident in 2027')).toContain('accident');
    expect(forbiddenHits('A calm and lucky year')).toEqual([]);
  });
});

describe('number validator', () => {
  it('collects numbers from facts, including strings like 2-5-8', () => {
    expect([...collectNumbers({ a: 1, b: ['2-5-8'], c: { d: 'Year 2027' } })].sort((x, y) => x - y)).toEqual([1, 2, 5, 8, 2027]);
  });
  it('ignores masked identifiers and catches invented numbers', () => {
    expect(numbersInText('Aadhaar XXXX-XXXX-0124 and mobile 98XXXXXX10')).toEqual([]);
    const r = checkNumbers('Your Moolank 1 and Personal Year 7 in 2030', new Set([1, 2030]));
    expect(r.ok).toBe(false);
    expect(r.unknown).toEqual([7]);
  });
  it('reads Devanagari digits', () => {
    expect(numbersInText('मूलांक १ और वर्ष २०२६')).toEqual([1, 2026]);
  });
});

describe('knowledge base & plan', () => {
  it('seed entries contain no digits and no banned terms', () => {
    for (const k of KNOWLEDGE_SEED) {
      expect(k.body, k.key).not.toMatch(/\d/);
      for (const b of BANNED_TERMS) expect(k.body.toLowerCase(), k.key).not.toContain(b);
    }
  });
  it('builds every section for a complete report and never exposes the full mobile/Aadhaar', () => {
    const plan = buildPlan(result, clientContext(result));
    expect(plan.map((s) => s.id)).toEqual(['intro', 'moolank', 'bhagyank', 'combination', 'loshu', 'missing', 'kua', 'forecast', 'lifePeriods', 'career', 'relationships', 'wellbeing', 'name', 'mobile', 'aadhaar', 'couple', 'remedies', 'closing']);
    const json = JSON.stringify(plan);
    expect(json).not.toContain('9876543210');
    expect(json).not.toContain(aadhaar);
  });
  it('system prompt carries the style guide', () => {
    const p = systemPrompt({ expertName: 'Acharya Test', brandName: 'Test Brand' }, 'hinglish');
    expect(p).toContain('Acharya Test');
    expect(p).toMatch(/Never predict death/);
    expect(p).toMatch(/only mention numbers.*FACTS/);
    expect(p).toMatch(/Never mention AI/);
    expect(p).toMatch(/Hinglish/);
  });
});

describe('template writer (offline)', () => {
  for (const language of ['en', 'hinglish'] as const) {
    it(`writes every section in ${language}, passing number validation with no banned or forbidden words`, async () => {
      const n = await generateNarrative(result, { language });
      expect(n.sections).toHaveLength(18);
      for (const s of n.sections) {
        expect(s.text.length, s.id).toBeGreaterThan(60);
        expect(s.warnings, s.id).toEqual([]);
        expect(forbiddenHits(s.text), s.id).toEqual([]);
        for (const b of BANNED_TERMS) expect(s.text.toLowerCase(), s.id).not.toContain(b);
        expect(s.text).not.toContain('9876543210');
        expect(s.text).not.toContain(aadhaar);
      }
      expect(n.sections[0].text).toContain('Rahul ji');
    });
  }
  it('works for many birth dates without validation warnings', async () => {
    const dates = ['01-01-2000', '29-02-1996', '31-12-1975', '11-11-1985', '22-04-1968', '07-07-2007', '19-09-1959', '05-10-2015'];
    for (const dob of dates) {
      const r = generateNumerology({ fullName: 'Anita Desai', gender: 'female', dob, maritalStatus: 'married', concerns: ['health', 'money'], mobile: '9123456780' }, { asOf });
      const n = await generateNarrative(r);
      for (const s of n.sections) expect(s.warnings, `${dob} ${s.id}`).toEqual([]);
    }
  });
  it('is deterministic and uses the cache by input hash', async () => {
    const cache = new MemoryCache();
    const a = await generateNarrative(result, { cache });
    const spy = vi.spyOn(cache, 'set');
    const b = await generateNarrative(result, { cache });
    expect(b).toEqual(a);
    expect(spy).not.toHaveBeenCalled();
    const c = await generateNarrative(result, { cache, language: 'hinglish' });
    expect(c.inputHash).not.toBe(a.inputHash);
  });
  it('expert review mode marks the narrative as awaiting review', async () => {
    expect((await generateNarrative(result, { expertReview: true })).status).toBe('awaiting_review');
  });
});

describe('LLM path (mocked provider)', () => {
  const only = ['moolank'] as const;
  it('regenerates a section whose numbers are not in the facts, then accepts a valid draft', async () => {
    const replies = [
      'Rahul ji, your Moolank 1 is ruled by the Sun, and in 2031 you will earn a 45 lakh raise.',
      'Rahul ji, born on the 28th, your Moolank 1 belongs to the Sun. Leadership comes naturally to you, and people look to you to begin things.',
    ];
    const provider: LlmProvider = { id: 'mock', model: 'm', complete: vi.fn(async () => replies.shift()!) };
    const n = await generateNarrative(result, { provider, sections: [...only] });
    expect(provider.complete).toHaveBeenCalledTimes(2);
    expect(n.sections[0].source).toBe('llm');
    expect(n.sections[0].attempts).toBe(2);
    const second = (provider.complete as ReturnType<typeof vi.fn>).mock.calls[1][0];
    expect(second.messages.at(-1).content).toMatch(/2031, 45/);
  });
  it('falls back to the template writer after repeated failures', async () => {
    const provider: LlmProvider = { id: 'mock', model: 'm', complete: vi.fn(async () => 'Your lucky number is 777 and there may be an accident.') };
    const n = await generateNarrative(result, { provider, sections: [...only], maxAttempts: 3 });
    expect(provider.complete).toHaveBeenCalledTimes(3);
    expect(n.sections[0].source).toBe('template');
    expect(n.sections[0].text).toContain('Moolank 1');
  });
  it('survives provider errors', async () => {
    const provider: LlmProvider = { id: 'mock', model: 'm', complete: vi.fn(async () => { throw new Error('timeout'); }) };
    const n = await generateNarrative(result, { provider, sections: [...only] });
    expect(n.sections[0].source).toBe('template');
  });
  it('Anthropic provider sends the expected request', async () => {
    const fetchMock = vi.fn(async () => new Response(JSON.stringify({ content: [{ type: 'text', text: 'Hello' }] }), { status: 200 }));
    const p = new AnthropicProvider({ provider: 'anthropic', model: 'test-model', apiKey: 'k', temperature: 0.5, timeoutMs: 1000 }, fetchMock as unknown as typeof fetch);
    expect(await p.complete({ system: 'S', messages: [{ role: 'user', content: 'U' }], maxTokens: 100 })).toBe('Hello');
    const [url, init] = fetchMock.mock.calls[0] as unknown as [string, RequestInit];
    expect(url).toBe('https://api.anthropic.com/v1/messages');
    const body = JSON.parse(String(init.body));
    expect(body).toMatchObject({ model: 'test-model', system: 'S', temperature: 0.5, max_tokens: 100 });
  });
  it('env config clamps temperature to 0.4–0.6 and defaults to the template writer', () => {
    expect(configFromEnv({ LLM_TEMPERATURE: '0.9' }).temperature).toBe(0.6);
    expect(configFromEnv({}).provider).toBe('template');
    expect(configFromEnv({ ANTHROPIC_API_KEY: 'x' }).provider).toBe('anthropic');
  });
});
